"""Result data models and score aggregation."""

import json
from typing import Any

from pydantic import BaseModel, Field, field_validator, model_validator

from ai_dev_toolkit._version import __version__
from ai_dev_toolkit.core.config import EvaluatorConfig


def clamp_score(score: float) -> float:
    """Clamp a floating point score to the [0.0, 1.0] range."""
    return max(0.0, min(1.0, float(score)))


def calculate_overall(
    relevance: float,
    completeness: float,
    faithfulness: float | None = None,
    config: EvaluatorConfig | None = None,
) -> float:
    """Calculate overall evaluation score with automatic weight renormalization.

    When faithfulness is None (e.g. context was not provided), the weights for
    relevance and completeness are renormalized proportionally.
    """
    cfg = config or EvaluatorConfig()
    rel = clamp_score(relevance)
    comp = clamp_score(completeness)

    if faithfulness is None:
        total_weight = cfg.relevance_weight + cfg.completeness_weight
        if total_weight <= 0.0:
            raise ValueError(
                "Sum of relevance and completeness weights must be > 0 "
                "when faithfulness is None"
            )
        score = (
            rel * cfg.relevance_weight + comp * cfg.completeness_weight
        ) / total_weight
    else:
        faith = clamp_score(faithfulness)
        total_weight = (
            cfg.relevance_weight + cfg.completeness_weight + cfg.faithfulness_weight
        )
        if total_weight <= 0.0:
            raise ValueError("Sum of all metric weights must be > 0")
        score = (
            rel * cfg.relevance_weight
            + comp * cfg.completeness_weight
            + faith * cfg.faithfulness_weight
        ) / total_weight

    return clamp_score(round(score, 4))


class MetricResult(BaseModel):
    """Result of an individual metric evaluation."""

    score: float = Field(description="Metric score in range [0.0, 1.0].")
    reasoning: str | None = Field(
        default=None,
        description="Explanation or justification generated by the judge.",
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Additional metric-specific diagnostic data.",
    )

    @field_validator("score", mode="before")
    @classmethod
    def _clamp_metric_score(cls, v: Any) -> float:
        return clamp_score(float(v))


class EvaluationMetadata(BaseModel):
    """Metadata regarding evaluation execution context and environment."""

    provider: str = Field(default="gemini", description="LLM provider name.")
    model: str = Field(default="", description="Model identifier used for evaluation.")
    toolkit_version: str = Field(
        default=__version__,
        description="Version of ai-dev-toolkit that produced this result.",
    )
    latency_ms: int | float | None = Field(
        default=None,
        description="Total execution latency in milliseconds.",
    )


class EvaluationResult(BaseModel):
    """Structured evaluation result combining all metric scores and metadata."""

    relevance: float = Field(
        description="Score for how well response addresses prompt [0.0, 1.0]."
    )
    completeness: float = Field(
        description="Score for coverage of prompt sub-questions [0.0, 1.0]."
    )
    faithfulness: float | None = Field(
        default=None,
        description=(
            "Score for factual grounding in provided context [0.0, 1.0], or None."
        ),
    )
    hallucination: float | None = Field(
        default=None,
        description=(
            "Computed hallucination score (1.0 - faithfulness) if context given."
        ),
    )
    overall: float = Field(description="Weighted composite score [0.0, 1.0].")
    reasoning: dict[str, str] = Field(
        default_factory=dict,
        description="Natural language reasoning explanations keyed by metric name.",
    )
    metadata: EvaluationMetadata = Field(
        default_factory=EvaluationMetadata,
        description="Evaluation metadata including provider, model, and latency.",
    )

    @field_validator("relevance", "completeness", "overall", mode="before")
    @classmethod
    def _clamp_required_scores(cls, v: Any) -> float:
        return clamp_score(float(v))

    @field_validator("faithfulness", mode="before")
    @classmethod
    def _clamp_faithfulness(cls, v: Any) -> float | None:
        if v is None:
            return None
        return clamp_score(float(v))

    @model_validator(mode="after")
    def _sync_hallucination(self) -> "EvaluationResult":
        if self.faithfulness is not None:
            computed_hallucination = clamp_score(round(1.0 - self.faithfulness, 4))
            self.hallucination = computed_hallucination
        else:
            self.hallucination = None
        return self

    def to_dict(self) -> dict[str, Any]:
        """Convert result model to standard dictionary format."""
        return self.model_dump()

    def to_json(self, indent: int | None = None) -> str:
        """Serialize result to a formatted JSON string."""
        return json.dumps(self.to_dict(), indent=indent)
